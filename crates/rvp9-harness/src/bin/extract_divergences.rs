//! `extract-divergences` — walks `notes/lld/*.md`, pulls each file's §7
//! "Deliberate divergences from libvpx" section out, and emits a single
//! aggregated review doc.
//!
//! Used at Phase 2e to seed `notes/divergence-ledger.md` from the 15 LLDs'
//! §7 sections without manually opening each file. The output is plain
//! markdown so it can be diffed against the existing ledger.
//!
//! Default: print the aggregated §7 dump to stdout.
//! With `--write <path>`: write to a file instead.
//!
//! Usage:
//!   cargo run --release --bin extract-divergences \
//!     -- [notes/lld] [--write notes/divergence-ledger-phase2e-draft.md]
//!
//! This tool is intentionally non-destructive: it never overwrites
//! `notes/divergence-ledger.md` itself. The Phase 2e human-driven merge
//! diffs the output of this tool against the ledger and folds in.

use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

/// Extract the §7 block from `content`. Returns the substring between
/// the first occurrence of `\n## 7.` (exclusive of the leading newline)
/// and the next `\n## 8.` (or end of file if §8 is missing).
fn extract_section_7(content: &str) -> Option<&str> {
    let start = content.find("\n## 7.")?;
    let after_marker = start + 1; // skip the leading newline
    let after = &content[after_marker..];
    let end_rel = after.find("\n## 8.").unwrap_or(after.len());
    Some(&after[..end_rel])
}

/// Locate the line where the §7 header begins. Used only for sanity-info
/// in the output (file:line jump-to-source hints).
fn section_7_line_number(content: &str) -> Option<usize> {
    content
        .lines()
        .enumerate()
        .find(|(_, line)| line.trim_start().starts_with("## 7."))
        .map(|(idx, _)| idx + 1)
}

#[derive(Debug)]
struct LldDivergences {
    file: String,
    line_of_section_7: Option<usize>,
    body: String,
}

fn collect(lld_dir: &Path) -> std::io::Result<Vec<LldDivergences>> {
    let mut out = Vec::new();
    for ent in fs::read_dir(lld_dir)?.flatten() {
        let p = ent.path();
        if p.extension().and_then(|s| s.to_str()) != Some("md") {
            continue;
        }
        let content = fs::read_to_string(&p)?;
        let Some(s7) = extract_section_7(&content) else {
            continue;
        };
        let file = p
            .file_name()
            .and_then(|s| s.to_str())
            .unwrap_or("?")
            .to_string();
        out.push(LldDivergences {
            file,
            line_of_section_7: section_7_line_number(&content),
            body: s7.to_string(),
        });
    }
    out.sort_by(|a, b| a.file.cmp(&b.file));
    Ok(out)
}

fn emit<W: Write>(w: &mut W, entries: &[LldDivergences]) -> std::io::Result<()> {
    writeln!(w, "# Phase 2e divergence draft (extracted from notes/lld/*.md §7)")?;
    writeln!(w)?;
    writeln!(
        w,
        "> Generated by `rvp9-harness::extract-divergences`. This is **not**\n\
         > the authoritative divergence ledger — it is an aggregated review\n\
         > doc for Phase 2e. The Phase 2e merge folds these entries into\n\
         > `notes/divergence-ledger.md` after deduplication against the\n\
         > existing seed entries from Stage 1 closure."
    )?;
    writeln!(w)?;
    writeln!(w, "## Summary")?;
    writeln!(w)?;
    writeln!(w, "| LLD | §7 line | bytes |")?;
    writeln!(w, "|---|---|---|")?;
    for e in entries {
        writeln!(
            w,
            "| `{}` | {} | {} |",
            e.file,
            e.line_of_section_7.map(|n| n.to_string()).unwrap_or_else(|| "?".into()),
            e.body.len()
        )?;
    }
    writeln!(w)?;
    writeln!(w, "---")?;
    writeln!(w)?;
    for e in entries {
        writeln!(w, "## From `notes/lld/{}` (§7 at line {})", e.file, e.line_of_section_7.map(|n| n.to_string()).unwrap_or_else(|| "?".into()))?;
        writeln!(w)?;
        // Demote the original `## 7.` header to `### §7 (from <file>)` so
        // the aggregated doc is structurally clean.
        for line in e.body.lines() {
            if line.trim_start().starts_with("## 7.") {
                writeln!(w, "### §7 — Deliberate divergences (from `{}`)", e.file)?;
            } else {
                writeln!(w, "{line}")?;
            }
        }
        writeln!(w)?;
        writeln!(w, "---")?;
        writeln!(w)?;
    }
    Ok(())
}

fn main() {
    let argv: Vec<String> = std::env::args().collect();
    let mut positional: Vec<String> = Vec::new();
    let mut write_to: Option<PathBuf> = None;
    let mut i = 1;
    while i < argv.len() {
        if argv[i] == "--write" {
            if let Some(v) = argv.get(i + 1) {
                write_to = Some(PathBuf::from(v));
                i += 2;
                continue;
            } else {
                eprintln!("error: --write requires an argument");
                std::process::exit(2);
            }
        }
        positional.push(argv[i].clone());
        i += 1;
    }
    let lld_dir = positional
        .first()
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("notes/lld"));

    if !lld_dir.is_dir() {
        eprintln!("error: not a directory: {}", lld_dir.display());
        std::process::exit(2);
    }

    let entries = match collect(&lld_dir) {
        Ok(v) => v,
        Err(e) => {
            eprintln!("error: collect: {e}");
            std::process::exit(2);
        }
    };

    if entries.is_empty() {
        eprintln!("(no LLDs with a §7 section found in {})", lld_dir.display());
        std::process::exit(2);
    }

    if let Some(path) = write_to {
        let f = match fs::File::create(&path) {
            Ok(f) => f,
            Err(e) => {
                eprintln!("error: create {}: {e}", path.display());
                std::process::exit(2);
            }
        };
        let mut bw = std::io::BufWriter::new(f);
        if let Err(e) = emit(&mut bw, &entries) {
            eprintln!("error: write: {e}");
            std::process::exit(2);
        }
        if let Err(e) = bw.flush() {
            eprintln!("error: flush: {e}");
            std::process::exit(2);
        }
        eprintln!(
            "wrote {} ({} LLDs, {} total bytes of §7 content)",
            path.display(),
            entries.len(),
            entries.iter().map(|e| e.body.len()).sum::<usize>(),
        );
    } else {
        let stdout = std::io::stdout();
        let mut bw = std::io::BufWriter::new(stdout.lock());
        if let Err(e) = emit(&mut bw, &entries) {
            eprintln!("error: write stdout: {e}");
            std::process::exit(2);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn extracts_section_7_between_8() {
        let doc = "## 1. Purpose\n\nx\n## 7. Divergences\n\n7.1 foo\n7.2 bar\n## 8. Open\n";
        let s7 = extract_section_7(doc).unwrap();
        assert!(s7.starts_with("## 7. Divergences"));
        assert!(s7.contains("7.1 foo"));
        assert!(s7.contains("7.2 bar"));
        assert!(!s7.contains("## 8. Open"));
    }

    #[test]
    fn extracts_section_7_at_eof() {
        let doc = "## 1. Purpose\n\n## 7. Divergences\nlast entry\n";
        let s7 = extract_section_7(doc).unwrap();
        assert!(s7.contains("last entry"));
    }

    #[test]
    fn missing_section_7_returns_none() {
        let doc = "## 1. Purpose\n## 8. Open\n";
        assert!(extract_section_7(doc).is_none());
    }

    #[test]
    fn line_number_finds_section_7() {
        let doc = "## 1. p\n\n## 7. Divergences\nbody\n";
        assert_eq!(section_7_line_number(doc), Some(3));
    }
}
