//! VP9 Pareto8 coefficient probability distribution (Task 2b.3).
//!
//! Mirrors libvpx `vp9_pareto8_full[COEFF_PROB_MODELS][MODEL_NODES]`
//! from `vp9/common/vp9_entropy.c:112-368` — a `255 × 8` table where
//! row `l - 1` gives the 8 derived probabilities for an
//! UNCONSTRAINED_NODES=3 "pivot" probability of `l`.
//!
//! Per libvpx (lines 99-104):
//!
//! > The cdf of the distribution is:
//! > `cdf(x) = 0.5 + 0.5 * sgn(x) * [1 - {alpha/(alpha + |x|)} ^ beta]`
//! > For a given beta and a given probability of the 1-node, alpha is
//! > first solved, and then the {alpha, beta} pair is used to generate
//! > the probabilities for the rest of the nodes.
//!
//! With β = 8. The table is consumed by `vp9_model_to_full_probs` (the
//! decoder reads the first 3 pivot probabilities from its FRAME_CONTEXT
//! coef_probs, then `memcpy`s row `pivot - 1` from this table into the
//! remaining 8 slots of the per-context 11-entry node-probability
//! vector — libvpx `vp9_entropy.c:1032`).

/// Number of pivot probabilities the Pareto8 table is indexed by
/// (`vp9_entropy.h:140`). Rows are indexed from 1..=255, i.e.
/// `vp9_pareto8_full[pivot - 1]`.
pub const COEFF_PROB_MODELS: usize = 255;

/// Number of derived node-probabilities per pivot
/// (`vp9_entropy.h:146`; = `ENTROPY_NODES(11) - UNCONSTRAINED_NODES(3)`).
pub const MODEL_NODES: usize = 8;

