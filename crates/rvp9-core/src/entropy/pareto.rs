#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_shape_matches_libvpx() {
        assert_eq!(VP9_PARETO8_FULL.len(), COEFF_PROB_MODELS);
        assert_eq!(VP9_PARETO8_FULL.len(), 255);
        assert_eq!(VP9_PARETO8_FULL[0].len(), MODEL_NODES);
        assert_eq!(VP9_PARETO8_FULL[0].len(), 8);
        // Total cells.
        assert_eq!(COEFF_PROB_MODELS * MODEL_NODES, 2040);
    }

    /// Spec-quoted spot checks at first / second / last rows.
    #[test]
    fn spec_spot_checks() {
        // pivot = 1 (libvpx :113).
        assert_eq!(VP9_PARETO8_FULL[0], [3, 86, 128, 6, 86, 23, 88, 29]);
        // pivot = 2 — verifiable directly against libvpx :114.
        assert_eq!(VP9_PARETO8_FULL[1], [6, 86, 128, 11, 87, 42, 91, 52]);
        // pivot = 255 (libvpx :367).
        assert_eq!(VP9_PARETO8_FULL[254], [255, 246, 247, 255, 239, 255, 253, 255]);
    }

    /// Per libvpx comment (`vp9_entropy.c:108-111`): every odd line is
    /// generated from the even lines by averaging. libvpx's `l` is
    /// 1-based, so 1-based-odd corresponds to 0-based-odd: in our array,
    /// `VP9_PARETO8_FULL[i]` for `i` odd equals
    /// `(VP9_PARETO8_FULL[i-1] + VP9_PARETO8_FULL[i+1]) >> 1`. We sample
    /// this invariant across the table — confirms transcription accuracy
    /// across the interior.
    ///
    /// Quick sanity: row 1 (`[6, 86, 128, 11, 87, 42, 91, 52]`) is
    /// the avg of row 0 (`[3, 86, 128, 6, 86, 23, 88, 29]`) and row 2
    /// (`[9, 86, 129, 17, 88, 61, 94, 76]`). Verified by hand.
    #[test]
    fn smoothing_invariant_sampled() {
        // i must be odd and strictly inside the interior so that i+1
        // is still a valid index. The last 0-indexed row is 254 (even)
        // so 253 is the largest valid odd row to test.
        for odd_i in [1usize, 3, 49, 99, 151, 201, 251, 253] {
            let prev = &VP9_PARETO8_FULL[odd_i - 1];
            let cur = &VP9_PARETO8_FULL[odd_i];
            let next = &VP9_PARETO8_FULL[odd_i + 1];
            for (((&p, &c), &n), node) in
                prev.iter().zip(cur.iter()).zip(next.iter()).zip(0..)
            {
                let expected = (p as u16 + n as u16) >> 1;
                assert_eq!(
                    c as u16, expected,
                    "smoothing failure at row {odd_i}, node {node}: prev={p}, next={n}"
                );
            }
        }
    }

    /// First-column monotonic property: column 0 is non-decreasing
    /// (the pivot probability — by construction it equals `l` rounded
    /// in a specific way; we only require monotone non-decreasing).
    #[test]
    fn column_0_monotonic() {
        for i in 1..COEFF_PROB_MODELS {
            assert!(
                VP9_PARETO8_FULL[i][0] >= VP9_PARETO8_FULL[i - 1][0],
                "column 0 not monotone at row {i}"
            );
        }
    }
}
